"""Train the neural bot's action-value network (numpy only).

Input: JSONL rows from scripts/neural-data.mjs  {x: features, mask: legal moves, q: big blinds per move}
Output: neural-weights.js (normalisation, layers, scale) plus a short report.
Usage: python3 scripts/neural-train.py out/neural-weights.js data1.jsonl [data2.jsonl ...]
"""
import json, sys
import numpy as np

out, *paths = sys.argv[1:]
rows = [json.loads(l) for p in paths for l in open(p) if l.strip()]
X = np.array([r['x'] for r in rows], dtype=np.float64)
M = np.array([[1.0 if (m and i > 0 and r['q'][i] is not None) else 0.0 for i, m in enumerate(r['mask'])] for r in rows])
Q = np.array([[0.0 if v is None else v for v in r['q']] for r in rows])
Q = np.clip(Q, -50, 50)
scale = float(np.std(Q[M > 0])) or 1.0
Y = Q / scale
n, d = X.shape
rng = np.random.default_rng(7)
idx = rng.permutation(n)
split = int(n * 0.85)
tr, va = idx[:split], idx[split:]
mean = X[tr].mean(0)
std = X[tr].std(0) + 1e-6
Xn = (X - mean) / std

sizes = [d, 64, 64, 5]
Ws = [rng.normal(0, np.sqrt(2 / sizes[i]), (sizes[i + 1], sizes[i])) for i in range(3)]
bs = [np.zeros(sizes[i + 1]) for i in range(3)]
params = Ws + bs
m1 = [np.zeros_like(p) for p in params]
m2 = [np.zeros_like(p) for p in params]
lr, b1, b2, wd = 1e-3, 0.9, 0.999, 1e-4
leak = 0.01

def forward(x):
    acts, pre = [x], []
    h = x
    for l in range(3):
        z = h @ Ws[l].T + bs[l]
        pre.append(z)
        h = np.where(z > 0, z, leak * z) if l < 2 else z
        acts.append(h)
    return acts, pre

def loss_on(ids):
    out_, _ = forward(Xn[ids])
    err = (out_[-1] - Y[ids]) * M[ids]
    # Huber in normalised units keeps rare all-in swings from dominating.
    a = np.abs(err)
    h = np.where(a < 1, 0.5 * err ** 2, a - 0.5)
    return h.sum() / M[ids].sum()

step = 0
best = (1e9, None)
patience = 0
for epoch in range(400):
    order = rng.permutation(tr)
    for s in range(0, len(order), 256):
        b = order[s:s + 256]
        acts, pre = forward(Xn[b])
        err = (acts[-1] - Y[b]) * M[b]
        g = np.clip(err, -1, 1) / max(1.0, M[b].sum())
        grads_W, grads_b = [None] * 3, [None] * 3
        for l in (2, 1, 0):
            grads_W[l] = g.T @ acts[l] + wd * Ws[l]
            grads_b[l] = g.sum(0)
            if l:
                g = (g @ Ws[l]) * np.where(pre[l - 1] > 0, 1, leak)
        grads = grads_W + grads_b
        step += 1
        for i, (p, gr) in enumerate(zip(params, grads)):
            m1[i] = b1 * m1[i] + (1 - b1) * gr
            m2[i] = b2 * m2[i] + (1 - b2) * gr ** 2
            p -= lr * (m1[i] / (1 - b1 ** step)) / (np.sqrt(m2[i] / (1 - b2 ** step)) + 1e-8)
    v = loss_on(va)
    if v < best[0] - 1e-4:
        best = (v, [p.copy() for p in params]); patience = 0
    else:
        patience += 1
    if epoch % 10 == 0:
        print(f'epoch {epoch} train {loss_on(tr[:5000]):.4f} val {v:.4f}')
    if patience > 25:
        break
for p, b in zip(params, best[1]):
    p[...] = b

# Decision quality on held-out rows: how often the network picks the move with
# the best rollout average, and the big blinds lost versus that move.
acts, _ = forward(Xn[va])
pred = np.where(M[va] > 0, acts[-1], -1e9)
target = np.where(M[va] > 0, Y[va], -1e9)
# Folding is a fixed 0; include it where legal.
fold_ok = np.array([rows[i]['mask'][0] for i in va])
pred[:, 0] = np.where(fold_ok, 0, -1e9)
target[:, 0] = np.where(fold_ok, 0, -1e9)
pick, opt = pred.argmax(1), target.argmax(1)
regret = (target[np.arange(len(va)), opt] - target[np.arange(len(va)), pick]) * scale
baseline_pick = np.where(M[va][:, 1] > 0, 1, 0)  # always check/call
base_regret = (target[np.arange(len(va)), opt] - target[np.arange(len(va)), baseline_pick]) * scale
report = {
    'rows': n, 'validation_rows': len(va), 'val_huber': round(best[0], 4),
    'agreement_with_best_rollout_move': round(float((pick == opt).mean()), 4),
    'avg_regret_bb': round(float(regret.mean()), 3),
    'always_call_regret_bb': round(float(base_regret.mean()), 3),
}
print(json.dumps(report))
layers = [{'W': np.round(Ws[l], 5).tolist(), 'b': np.round(bs[l], 5).tolist()} for l in range(3)]
weights = {'scale': round(scale, 5), 'mean': np.round(mean, 6).tolist(), 'std': np.round(std, 6).tolist(), 'layers': layers}
with open(out, 'w') as f:
    f.write('// Generated by scripts/neural-train.py from simulated hands. Do not edit by hand.\n')
    f.write(f'export const NEURAL_REPORT = {json.dumps(report)};\n')
    f.write(f'export const NEURAL_WEIGHTS = {json.dumps(weights, separators=(",", ":"))};\n')
